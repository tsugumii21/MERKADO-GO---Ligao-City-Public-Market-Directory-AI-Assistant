/// Purges all existing demo stalls from Firestore and seeds all 134 real market stalls.
Future<int> purgeAndSeedStalls({
  void Function(String message)? onProgress,
}) async {
  final firestore = FirebaseFirestore.instance;
  final stallsCollection = firestore.collection('stalls');

  onProgress?.call('Fetching existing stalls in Firestore...');
  final existingSnapshot = await stallsCollection.get();

  if (existingSnapshot.docs.isNotEmpty) {
    onProgress?.call('Purging ${existingSnapshot.docs.length} old stall records...');
    // Delete existing documents in batches of 400
    const batchSize = 400;
    for (var i = 0; i < existingSnapshot.docs.length; i += batchSize) {
      final batch = firestore.batch();
      final end = (i + batchSize < existingSnapshot.docs.length)
          ? i + batchSize
          : existingSnapshot.docs.length;
      for (var j = i; j < end; j++) {
        batch.delete(existingSnapshot.docs[j].reference);
      }
      await batch.commit();
    }
  }

  onProgress?.call('Seeding ${kMarketVendorsSeedData.length} real market stalls...');
  // Seed in batches of 400
  const batchSize = 400;
  int seededCount = 0;

  for (var i = 0; i < kMarketVendorsSeedData.length; i += batchSize) {
    final batch = firestore.batch();
    final end = (i + batchSize < kMarketVendorsSeedData.length)
        ? i + batchSize
        : kMarketVendorsSeedData.length;

    for (var j = i; j < end; j++) {
      final vendor = kMarketVendorsSeedData[j];
      final stallId = vendor['stall_id'] as String;
      final docRef = stallsCollection.doc(stallId);

      final stallDoc = <String, dynamic>{
        'id': vendor['id'],
        'stallId': stallId,
        'stall_id': stallId,
        'name': vendor['name'],
        'category': vendor['category'],
        'categories': List<String>.from(vendor['categories'] as List),
        'section': vendor['section'],
        'stallNumber': vendor['stall_number'],
        'stall_number': vendor['stall_number'],
        'address': vendor['address'],
        'products': <String>[],
        'photoUrls': <String>[],
        'openTime': '5:00 AM',
        'closeTime': '6:00 PM',
        'daysOpen': <String>[
          'Monday',
          'Tuesday',
          'Wednesday',
          'Thursday',
          'Friday',
          'Saturday',
          'Sunday',
        ],
        'latitude': 13.2419233,
        'longitude': 123.5385460,
        'isActive': true,
        'isOpen': true,
        'status': 'open',
        'tags': <String>[],
        'updatedAt': FieldValue.serverTimestamp(),
      };

      batch.set(docRef, stallDoc);
      seededCount++;
    }

    await batch.commit();
    onProgress?.call('Saved $seededCount / ${kMarketVendorsSeedData.length} stalls to Firestore...');
  }

  return seededCount;
}

/// Legacy backward compatible seed alias
Future<void> seedStallData() async {
  await purgeAndSeedStalls();
}

